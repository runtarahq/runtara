//! Canonical WIT contracts of every runtara component.
//!
//! Packages are grouped by who may import them, so each package is one
//! privilege class and one versioning cadence:
//!
//! - `runtara:agent`: the shared vocabulary and the agent export shape;
//! - `runtara:host`: services any ordinary agent and every workflow may import;
//! - `runtara:workflow`: the host ABI of compiled workflow logic only;
//! - `runtara:workflow-stdlib`: the compiler-private JSON stdlib component;
//! - `runtara:trusted`: approved trusted agents only;
//! - `runtara:control`: the control agent only.
//!
//! Each agent additionally exports its own `runtara:agent-<id>` package,
//! generated by [`agent_package`]; the unique package name is what lets
//! composition tell agents apart.
//!
//! # Versioning
//!
//! A parked run wakes on the artifact it was built from, possibly after the
//! host was upgraded, and wasmtime lifts records, variants and enums exactly.
//! So released WIT is never edited, only versioned:
//!
//! - An **additive** change (a new function or interface in a package) bumps
//!   the package minor version. The host links only the newest minor: the
//!   wasmtime linker resolves an import of `@1.0.0` against a semver-compatible
//!   `@1.x` definition.
//! - **Any change to an existing function or type** bumps the major version,
//!   and the host links the old major beside the new one until no parked run
//!   needs it.

/// Expands to the version shared by every runtara WIT package. Textually
/// scoped, so it reaches every module below.
macro_rules! v {
    () => {
        "1.0.0"
    };
}

/// Version shared by every runtara WIT package.
pub const VERSION: &str = v!();

/// Directory holding one sub-directory of WIT per package. Guest crates and
/// proc macros point `wit_bindgen` here instead of at relative paths.
pub const WIT_DIR: &str = concat!(env!("CARGO_MANIFEST_DIR"), "/wit");

/// `runtara:agent`: the shared vocabulary and the agent export shape.
pub mod agent {
    pub const PACKAGE: &str = concat!("runtara:agent@", v!());
    /// `error-info`, used by every component.
    pub const TYPES: &str = concat!("runtara:agent/types@", v!());
    /// Any version of the types interface.
    pub const TYPES_PREFIX: &str = "runtara:agent/types@";
    /// Continuation delivery, imported by suspending agents.
    pub const CONTINUATION: &str = concat!("runtara:agent/continuation@", v!());
    /// The reference capabilities shape the host binds against.
    pub const CAPABILITIES: &str = concat!("runtara:agent/capabilities@", v!());
    pub const WIT: &str = include_str!("../wit/agent/runtara-agent.wit");
}

