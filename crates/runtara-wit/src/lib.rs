/// The resolved WASI inputs the workflow compiler imports (managed by
/// `wit-deps` under `wit/deps`).
pub mod wasi {
    pub const IO_POLL_WIT: &str = include_str!("../wit/deps/io/poll.wit");
    pub const MONOTONIC_CLOCK_WIT: &str = include_str!("../wit/deps/clocks/monotonic-clock.wit");
    pub const MONOTONIC_CLOCK: &str = "wasi:clocks/monotonic-clock@0.2.3";
}

/// Every package as `(file name, WIT text)`, in dependency order: a package
/// comes after every package it `use`s. This is the only place that knows the
/// order.
pub const PACKAGES: &[(&str, &str)] = &[
    ("runtara-agent.wit", agent::WIT),
    ("runtara-host.wit", host::WIT),
    ("runtara-workflow.wit", workflow::WIT),
    ("runtara-workflow-stdlib.wit", stdlib::WIT),
    ("runtara-trusted.wit", trusted::WIT),
    ("runtara-control.wit", control::WIT),
];

/// A `wit_parser` resolve holding every runtara package once, after the WASI
/// clock and poll interfaces the workflow compiler imports. Callers add
/// their own packages (per-agent packages, a workflow world) on top; a world
/// imports only what it names, so the unused packages are harmless.
#[cfg(any(test, feature = "resolve"))]
pub fn resolve() -> Result<wit_parser::Resolve, String> {
    let mut resolve = wit_parser::Resolve::default();
    let wasi = [
        ("wasi-io-poll.wit", wasi::IO_POLL_WIT),
        ("wasi-monotonic-clock.wit", wasi::MONOTONIC_CLOCK_WIT),
    ];
    for (name, wit) in wasi.iter().chain(PACKAGES) {
        resolve
            .push_str(name, wit)
            .map_err(|error| format!("{name}: {error:#}"))?;
    }
    Ok(resolve)
}

/// Which interfaces a generated `runtara:agent-<id>` package declares.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub struct AgentShape {
    /// The compiler's isolated-agent variant: `scoped-capabilities-v3`, whose
    /// `invoke` also takes the logical call context.
    pub scoped: bool,
    /// A suspending agent: import the continuation of the operation it runs in.
    pub suspendable: bool,
    /// Also export `runtara:trusted/execution`.
    pub trusted: bool,
    /// Import the control executor and API, and export
    /// `runtara:control/execution`.
    pub control: bool,
}

/// Name of the per-agent capabilities interface for `shape`.
pub fn capabilities_interface(shape: AgentShape) -> &'static str {
    if shape.scoped {
        "scoped-capabilities-v3"
    } else {
        "capabilities"
    }
}

/// The `runtara:agent-<id>` package an agent exports, and the compiler
/// imports, for `id` (the agent id in kebab case).
pub fn agent_package(id: &str, shape: AgentShape) -> String {
    let version = VERSION;
    let interface = capabilities_interface(shape);
    // The scoped isolation adapter's private interface keeps the bare list:
    // the host adapter, not the agent, owns suspension there.
    let result = if shape.scoped { "list<u8>" } else { "outcome" };
    let context = if shape.scoped {
        "\n        path: string, call-site: u32, activation: u32, attempt: u64,"
    } else {
        ""
    };
    let mut wit = format!(
        "package runtara:agent-{id}@{version};\n\
         \n\
         interface {interface} {{\n    \
             use runtara:agent/types@{version}.{{error-info, outcome}};\n    \
             invoke: async func(\n        \
                 capability-id: string,\n        \
                 input: list<u8>,{context}\n    \
             ) -> result<{result}, error-info>;\n\
         }}\n"
    );
    wit.push_str("\nworld agent {\n");
    if shape.suspendable {
        wit.push_str(&format!("    import {};\n", agent::CONTINUATION));
    }
    if shape.control {
        wit.push_str(&format!("    import {};\n", control::EXECUTOR));
        wit.push_str(&format!("    import {};\n", control::API));
    }
    wit.push_str(&format!("    export {interface};\n"));
    if shape.trusted {
        wit.push_str(&format!("    export {};\n", trusted::EXECUTION));
    }
    if shape.control {
        wit.push_str(&format!("    export {};\n", control::EXECUTION));
    }
    wit.push_str("}\n");
    wit
}

