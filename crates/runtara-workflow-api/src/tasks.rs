//! Child runs, `/v1/tasks`: embedded child workflows and isolated or scoped
//! agents, each in its own sandbox, started and joined by the parent.

use serde::{Deserialize, Serialize};

use crate::{ErrorInfo, Wake};

/// The `Runtara-Task` metadata of `POST /v1/tasks`; the body is the child's
/// input.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
pub struct TaskStart {
    /// The child binding of the run's package.
    pub binding: String,
    pub entry: TaskEntry,
    pub context: TaskContext,
}

/// What a child run invokes: `{"capability": id}` or `"workflow"`.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub enum TaskEntry {
    Capability(String),
    Workflow,
}

/// The call site of a child run, generated by the parent and validated by the
/// host against the parent's own scope. Not an authorization token.
#[derive(Clone, Debug, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
pub struct TaskContext {
    pub path: String,
    pub attempt: u64,
}

/// The answer to `POST /v1/tasks`.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
pub struct TaskStarted {
    pub task_id: String,
    /// The child's run, for a child that is a run of its own (entry
    /// `workflow`): the same id as `task_id`, which a parent can wait on.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub instance_id: Option<String>,
}

/// A terminal child run, published only after its execution was destroyed.
/// `GET /v1/tasks/{taskId}/outcome` carries the kind in
/// [`crate::headers::OUTCOME`] and the value as its body.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum TaskOutcome {
    /// Body: the raw output bytes.
    Completed(Vec<u8>),
    /// Body: JSON [`ErrorInfo`].
    Failed(ErrorInfo),
    /// Body: the JSON wakes. Interim, until a parked child is a parked run of
    /// its own that the parent waits on.
    Suspended(Vec<Wake>),
    Cancelled,
    TimedOut,
    /// Body: `{message}`.
    Trapped(String),
}

impl TaskOutcome {
    /// The `Runtara-Outcome` value of this outcome.
    pub fn kind(&self) -> &'static str {
        match self {
            Self::Completed(_) => "completed",
            Self::Failed(_) => "failed",
            Self::Suspended(_) => "suspended",
            Self::Cancelled => "cancelled",
            Self::TimedOut => "timed-out",
            Self::Trapped(_) => "trapped",
        }
    }

    /// The response body of this outcome.
    pub fn body(&self) -> Vec<u8> {
        match self {
            Self::Completed(bytes) => bytes.clone(),
            Self::Failed(error) => serde_json::to_vec(error).expect("error info serializes"),
            Self::Suspended(wakes) => serde_json::to_vec(wakes).expect("wakes serialize"),
            Self::Cancelled | Self::TimedOut => Vec::new(),
            Self::Trapped(message) => {
                serde_json::to_vec(&serde_json::json!({ "message": message }))
                    .expect("a message serializes")
            }
        }
    }

    /// The outcome `kind` with `body`, as [`Self::kind`] and [`Self::body`]
    /// wrote them.
    pub fn parse(kind: &str, body: &[u8]) -> Result<Self, String> {
        Ok(match kind.trim() {
            "completed" => Self::Completed(body.to_vec()),
            "failed" => Self::Failed(
                serde_json::from_slice(body).map_err(|e| format!("failed outcome: {e}"))?,
            ),
            "suspended" => Self::Suspended(
                serde_json::from_slice(body).map_err(|e| format!("suspended outcome: {e}"))?,
            ),
            "cancelled" => Self::Cancelled,
            "timed-out" => Self::TimedOut,
            "trapped" => {
                #[derive(Deserialize)]
                struct Trapped {
                    message: String,
                }
                let trapped: Trapped =
                    serde_json::from_slice(body).map_err(|e| format!("trapped outcome: {e}"))?;
                Self::Trapped(trapped.message)
            }
            other => return Err(format!("unknown task outcome `{other}`")),
        })
    }
}

/// The answer to `POST /v1/tasks/{taskId}/cancel`.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "kebab-case")]
pub enum CancelStatus {
    Requested,
    AlreadyRequested,
    AlreadyTerminal,
}

/// `{status}` of a cancel request.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
pub struct CancelAnswer {
    pub status: CancelStatus,
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn metadata_and_outcomes_have_their_wire_forms() {
        let start: TaskStart = serde_json::from_str(
            r#"{"binding":"b","entry":{"capability":"run"},"context":{"path":"p","attempt":2}}"#,
        )
        .unwrap();
        assert_eq!(start.entry, TaskEntry::Capability("run".into()));
        let workflow: TaskEntry = serde_json::from_str(r#""workflow""#).unwrap();
        assert_eq!(workflow, TaskEntry::Workflow);
        assert_eq!(
            serde_json::to_string(&CancelAnswer {
                status: CancelStatus::AlreadyRequested
            })
            .unwrap(),
            r#"{"status":"already-requested"}"#
        );
        for outcome in [
            TaskOutcome::Completed(b"42".to_vec()),
            TaskOutcome::Suspended(vec![Wake::At(5)]),
            TaskOutcome::Cancelled,
            TaskOutcome::TimedOut,
            TaskOutcome::Trapped("boom".into()),
        ] {
            assert_eq!(
                TaskOutcome::parse(outcome.kind(), &outcome.body()).unwrap(),
                outcome
            );
        }
    }
}
