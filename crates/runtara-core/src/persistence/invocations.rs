//! Atomic persistence of a root execution's lease: which host launch owns a
//! running instance, and at which epoch.
//!
//! A backend must provide every operation atomically; checking a token and
//! later issuing an unfenced write does not implement this contract.
use async_trait::async_trait;

/// Current host owner of a root execution.
#[derive(Clone, Debug, PartialEq, Eq, serde::Serialize, serde::Deserialize)]
pub struct InvocationLease {
    /// Tenant resolved by trusted execution admission.
    pub tenant_id: String,
    /// Public root instance identity.
    pub instance_id: String,
    /// Opaque launch identity, generated by the host.
    pub owner: String,
    /// Monotonic root lease generation, allocated by the store.
    pub epoch: i64,
}

/// Durable owner facts for crash recovery before an exact revocation/CAS claim.
#[derive(Clone, Debug, PartialEq, Eq, serde::Serialize, serde::Deserialize)]
pub struct InvocationLeaseState {
    /// Current owner and its epoch.
    pub lease: InvocationLease,
    /// False after revocation; revocation does not establish that teardown ended.
    pub active: bool,
}

/// A rejected mutation never changes lease state.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum FenceRejection {
    /// Invalid or unrepresentable identity/counter.
    InvalidIdentity,
    /// No root owned by this tenant; do not disclose another tenant's state.
    UnknownRoot,
    /// The root is not running.
    InactiveRoot,
    /// Missing, revoked or superseded lease.
    LeaseMismatch,
}

/// Storage failures are distinct from an expected arbitration rejection.
#[derive(Debug, thiserror::Error)]
pub enum InvocationFenceError {
    /// The requested transition did not own the current state.
    #[error("invocation fence rejected: {0:?}")]
    Rejected(FenceRejection),
    /// Backend failure; callers must not treat this as permission to proceed.
    #[error("invocation fence storage failed: {0}")]
    Storage(String),
}

/// Result of an atomic invocation operation.
pub type FenceResult<T> = Result<T, InvocationFenceError>;

/// Validate bounded, nonempty opaque identities without interpreting graph syntax.
pub fn validate_identity(value: &str) -> FenceResult<()> {
    if value.is_empty() || value.len() > 4096 || value.contains('\0') {
        return Err(InvocationFenceError::Rejected(
            FenceRejection::InvalidIdentity,
        ));
    }
    Ok(())
}

/// Optional capability exposed by [`super::Persistence::invocation_fences`].
/// All methods serialize with root terminal transitions and each other. A root
/// lease must be revoked before another owner can claim it. Revocation fences
/// writes; it does not stop the old execution. The runner must still join it
/// before releasing its capacity.
#[async_trait]
pub trait InvocationFences: Send + Sync {
    /// Inspect the current owner for a tenant-owned root, including parked or
    /// terminal roots. A root with no lease returns None. This snapshot grants
    /// no mutation authority by itself; subsequent transitions still use CAS.
    async fn get_invocation_lease(
        &self,
        tenant: &str,
        instance: &str,
    ) -> FenceResult<Option<InvocationLeaseState>>;

    /// Claim first ownership with `None`, or replace exactly the revoked epoch.
    /// A retry with the same owner and expected epoch returns the same lease.
    /// Running owners cannot be silently displaced, and epochs never repeat.
    async fn claim_invocation_lease(
        &self,
        tenant: &str,
        instance: &str,
        owner: &str,
        expected_epoch: Option<i64>,
    ) -> FenceResult<InvocationLease>;
    /// Revoke exactly this owner, idempotently. Works after root termination.
    /// Leaving Running also revokes execution ownership atomically. Resuming
    /// requires a new lease.
    async fn revoke_invocation_lease(&self, lease: &InvocationLease) -> FenceResult<()>;
}
